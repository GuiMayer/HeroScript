const assert = require('node:assert/strict');
const path = require('node:path');
const { RealDeckClient } = require('./real-deck-client.cjs');
async function main() {
  const game = await new RealDeckClient(process.argv[2] || 'http://localhost:15262', process.argv[3] || path.resolve('.runtime/clash-real-deck-fixture/runs')).start(3);
  const execute = async id => { const legal = (await game.legal()).candidates; const candidate = legal.find(entry => entry.cardDefinitionId === id || entry.actionId === id); assert.ok(candidate, `Missing ${id}`); return game.execute(candidate); };
  const before = game.zone('draw').length; await execute('clash_wild_draw4');
  assert.equal(game.zone('hand', 'dealer').length, 11); assert.equal(game.zone('draw').length, before - 4);
  assert.equal(game.resource('dealer', 'clash_draw2_pending'), 0); assert.equal(game.resource('player', 'clash_energy'), 1);
  await execute('clash_choose_red');
  await execute('clash_red_reverse'); await execute('clash_red_skip'); await execute('clash_red_7');
  await game.end(); assert.equal(game.resource('player', 'clash_draw2_pending'), 2);
  await execute('clash_red_draw2'); await game.end();
  assert.equal(game.resource('player', 'clash_draw2_pending'), 0);
  await execute('clash_green_draw2'); await execute('clash_shout_clash'); await game.end();
  await execute('clash_green_2');
  const combat = await game.api(`/api/v1/combats/${game.combatId}`);
  assert.equal(combat.status, 'VICTORY'); assert.equal(game.zone('hand', 'player').length, 0);
  console.log('PASS: real +4 stays separate; Reverse/Skip retain play; player empties actual hand and wins');
  let available = await game.api(`/api/v1/runs/${game.runId}/available-commands`);
  const resolve = available.commands.find(entry => entry.type === 'RESOLVE_COMBAT'); assert.ok(resolve);
  await game.api(`/api/v1/runs/${game.runId}/commands`, { commandId: crypto.randomUUID(), type: resolve.type, expectedSequence: resolve.expectedSequence, expectedStep: resolve.expectedStep, payload: resolve.validPayload });
  available = await game.api(`/api/v1/runs/${game.runId}/available-commands`);
  const next = available.commands.find(entry => entry.type === 'ADVANCE_NODE');
  assert.ok(!next || !next.targetNodeIds?.length, 'There must be no other opponent after the match');
  const fresh = await new RealDeckClient(game.base, game.store).start(3);
  assert.notEqual(fresh.runId, game.runId);
  assert.equal(fresh.zone('hand', 'player').length, 7); assert.equal(fresh.zone('hand', 'dealer').length, 7);
  fresh.assertConservation();
  console.log('PASS: one opponent only; a new match starts with a fresh conserved 108-card deck');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
